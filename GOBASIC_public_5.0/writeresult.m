version_tag = '# This file is generated by GOBASIC v5.0';
res_head_fmt = '%-16s | %12s %12s\n';
res_tbl_fmt = {'%-16s | %12.2f %12.2f\n';
               '%-16s | %12.2f %12.2f\n';
               '%-16s | %12.2f %12.2f\n';
               '%-16s | %12.2f %12.2f\n';
               '%-16s | %12.3e %12.3e\n';};
q_head_fmt = '%-16s | %12s %10s %10.6s %12s\n';
q_fmt = '%-16s | %12.6f %10.4f %10.6f %12.6f\n';
res_head_tag = {'Log10NT'; 'Log10NT_err';
                'fwhm (km/s)'; 'fwhm_err';
                'Temp (K)'; 'Temp_err';
                'shift (km/s)'; 'shift_err';
                'NT (cm^-2)'; 'NT_err';};
result_tag = '# Row-wise: fitted parameter matrix x; uncertainty matrix';
fit_tag = 'obsfreq,obsint,previousfit';
if isempty(label)
    label = cell(comp_num,1);
    for n=1:comp_num
        label{n} = strcat('fit',int2str(n));
    end
end
for n=1:comp_num
    fit_tag = strcat(fit_tag,',',label{n});
end
fit_tag = strcat(fit_tag,',sum_fits');

res_id = fopen(strcat(outputpath,outputname,'Results.csv'),'w');
res_tbl_id = fopen(strcat(outputpath,outputname,'Table.txt'),'w');
fit_id = fopen(strcat(outputpath,outputname,'Fit.csv'),'w');

% write Table.txt
fprintf(res_tbl_id,'%s\n',version_tag);
for m=1:5
    fprintf(res_tbl_id,'\n%40s\n',repmat('*',1,44));
    fprintf(res_tbl_id,res_head_fmt,'Molecule',res_head_tag{2*m-1},res_head_tag{2*m});
    for n=1:comp_num
        fprintf(res_tbl_id,res_tbl_fmt{m},label{n},results(2*m-1:2*m,n));
    end
end
fprintf(res_tbl_id,'\n\nPartition function interpolation coefficients\n');
fprintf(res_tbl_id,'Q(T) = a1 * T^a2 * (a3 + exp(a4/T))\n');
fprintf(res_tbl_id,q_head_fmt,'Molecule','a1','a2','a3','a4');
for n=1:comp_num
    fprintf(res_tbl_id,q_fmt,label{n},aco{n});
end

% write results.csv and fit.csv tags
fprintf(res_id,'%s\n',version_tag,result_tag);
fprintf(fit_id,'%s\n',version_tag,fit_tag);

% close files
fclose(res_id);
fclose(res_tbl_id);
fclose(fit_id);

% print information
fprintf(strcat('\n',outputpath,outputname,'Table.txt Saved!\n'));

% append data to Results.csv
dlmwrite(strcat(outputpath,outputname,'Results.csv'),...
         vertcat(x,uncertainty),'-append','precision',10);
fprintf(strcat(outputpath,outputname,'Resutls.csv Saved!\n'));

% append data to Fit.csv
dlmwrite(strcat(outputpath,outputname,'Fit.csv'),...
         horzcat(obsfreq,obsint,update,fits,sum(fits,2)),'-append',...
         'precision',10);
fprintf(strcat(outputpath,outputname,'Fit.csv Saved!\n'));
