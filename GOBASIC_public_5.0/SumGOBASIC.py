# encoding = utf8

''' This script is used to concatenate indivudual GOBASIC fitted files
into a single large one.'''

import numpy as np
import sys
import re
import argparse

# parse arguments
parser = argparse.ArgumentParser(description=__doc__,
                                 epilog='--- Luyao Zou, June 2015 ---')
parser.add_argument('file', nargs='+', help='input file name')
parser.add_argument('-o', '--out', nargs=1, help='output file name')
args = parser.parse_args()

in_list = args.file
if args.out:
    out_name = args.out[0]
else:
    out_name = 'GOBASIC_Concatenated.csv'

# read through the input file list
# all information are stored in nested lists
print('>> Processing')
version = []
header = []
data_table = []
print('>> Loading files ', end='')

for in_name in in_list:
    sys.stdout.write('>')
    sys.stdout.flush()
    with open(in_name, newline='') as in_file:
        # read version and header info
        version.append(re.search('\d.\d', in_file.readline()).group())
        header.append(in_file.readline())
    # load data table
    obsdata = np.loadtxt(in_name, delimiter=',', skiprows=2)
    data_table.append(obsdata)

# write obsfreq, obsint and previousfit into output data table
print('\n>> Concatenating ', end='')
out_table = np.compress([True, True, True], data_table[0], axis=1)
# write data tables into output table
for data in data_table:
    # Select from the 4th column through the end-1(th) column of the data
    # table, which are columns for individual components
    sys.stdout.write('>')
    sys.stdout.flush()
    out_table = np.concatenate((out_table, data[:,3:-1]), axis=1)
# calculate sum of all components
sum_fit = np.sum(out_table[:,3:], axis=1)
# convert sum_fit to matrix format otherwise it will always be a row vector
sum_fit = np.mat(sum_fit)
out_table = np.concatenate((out_table, np.transpose(sum_fit)), axis=1)
# *** output table complete! ***

# generate output header
out_header = 'obsfreq,obsint,previousfit,'
for h in header:
    cols = h.split(',')
    # this is a relatively stupid way. select column names of components
    for col_name in cols[3:-1]:
        out_header += col_name + ','
out_header += 'sum_fits'

# generate version information
out_version = ('# This file is generated by GOBASIC v{0:s}, '.format(max(version))
               + 'and concatenated by python3.4 script SumGOBASIC.py\n')
out_header = out_version + out_header

# output concatenated table
np.savetxt(out_name, out_table, fmt='%.10g', newline='\n', delimiter=',',
           header=out_header, comments='')
print('\n>> Output file saved as {:s}'.format(out_name))
